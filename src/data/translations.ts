export function getLocalized(obj: any, lang: Language): string {
  if (!obj) return '';
  if (typeof obj === 'string') return obj;
  if (obj[lang]) return obj[lang];
  if (obj['es']) return obj['es'];
  if (obj['en']) return obj['en'];
  return Object.values(obj)[0] as string || '';
}
